// Helper to generate trend points
function generateChartPoints(basePrice: number, volatility: number, count: number, trend: number) {
  const points = [];
  let current = basePrice;
  const now = new Date();
  
  for (let i = count; i >= 0; i--) {
    const timeLabel = new Date(now.getTime() - i * 86400000 * (365 / Math.max(count, 1)))
      .toLocaleDateString('zh-TW', { month: 'numeric', day: 'numeric' });
    
    const change = (Math.random() - 0.48 + trend) * volatility;
    current = Math.max(current * (1 + change), basePrice * 0.4);
    
    points.push({
      time: timeLabel,
      price: Number(current.toFixed(2)),
      open: Number((current * (1 - Math.random() * 0.01)).toFixed(2)),
      high: Number((current * (1 + Math.random() * 0.015)).toFixed(2)),
      low: Number((current * (1 - Math.random() * 0.015)).toFixed(2)),
      close: Number(current.toFixed(2)),
      volume: Math.floor(Math.random() * 50000) + 10000,
    });
  }
  return points;
}

